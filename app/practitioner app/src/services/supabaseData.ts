/**
 * NOTE ON TYPES vs. THE POSTGRES SCHEMA
 * ------------------------------------
 * The practitioner app talks to the `public` schema documented in `supabase/schema.sql`.
 * A few things are easy to get wrong, so they are pinned down here:
 *
 * 1. `users.id`, `hubs.id`, `courses.id` … are **uuid** (generated by Postgres).
 *    `session_registers.practitioner_id`, `check_in_logs.learner_id`,
 *    `posted_assessment.created_by`, `module_assignments.created_by` and friends are plain
 *    **text** columns with no FK — so we always pass the uuid *string* of a `users.id`,
 *    never an auth uid and never a number.
 * 2. `session_registers.hub_id` is text but `hubs.id` is uuid. We therefore only ever write
 *    `hub.id.toString()` values that came from `fetchHubs()`.
 * 3. `modules.id` / `courses.id` in `module_assignments`: `course_id` is text, `module_id`
 *    has a FK to `modules(id)` (text PK). Both must reference existing rows.
 * 4. Every enum-ish column has a CHECK constraint (`kind`, `level`, `competency_area`,
 *    `status`, `role`). Never send a free-typed string for those — use the constants in
 *    `./schema` and validate before insert (see `assert*` helpers below).
 * 5. Text columns carry `length(btrim(x)) >= n` checks; `boundedText()` trims and validates
 *    with the same limits so a write can't fail on whitespace.
 */

