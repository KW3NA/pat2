/** Email + password sign-in for practitioners (Supabase Auth). */
export async function signIn(email: string, password: string) {
  const { data, error } = await supabase.auth.signInWithPassword({
    email: email.trim().toLowerCase(),
    password,
  });
  if (error) throw new Error(error.message);
  return data;
}

export async function signUp(email: string, password: string, name: string) {
  const cleanName = boundedText(name, 2, 100) ?? 'Practitioner';
  const cleanEmail = email.trim().toLowerCase();
  const { data, error } = await supabase.auth.signUp({
    email: cleanEmail,
    password,
    options: { data: { full_name: cleanName, role: 'practitioner' satisfies UserRole } },
  });
  if (error) throw new Error(error.message);
  if (data.user) {
    // Mirror into public.users so downstream text ids resolve to a real practitioner row.
    // users.role / status / verification_status all carry CHECK constraints — the values
    // below are exactly what the schema allows. `id`, `created_at`, `updated_at` come from
    // Postgres defaults (gen_random_uuid() / now()).
    const { error: profileError } = await supabase.from('users').upsert(
      {
        auth_id: data.user.id,
        role: 'practitioner' satisfies UserRole,
        name: cleanName,
        email: cleanEmail,
        status: 'active',
        verification_status: 'pending',
        updated_at: new Date().toISOString(),
      },
      { onConflict: 'auth_id' },
    );
    throwIfDbError(profileError, 'Account created, but the practitioner profile could not be saved.');
  }
  return data;
}

export async function signOut() {
  await supabase.auth.signOut();
}

