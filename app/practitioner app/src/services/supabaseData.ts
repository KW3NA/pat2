export type NewAssessment = {
  /** posted_assessments.id has no default — the caller supplies a stable text id */
  id: string;
  title: string;
  description: string;
  kind: AssessmentKind;
  competency_area?: CompetencyArea | null;
  level: Level;
  questions?: unknown[];
  practical_task_ids?: string[];
  hub_id: string;
  created_by: string;
  creator_name: string;
  is_published?: boolean;
  due_at?: string | null;
  max_attempts?: number;
};

export async function createAssessment(input: NewAssessment): Promise<PostedAssessment> {
  const id = input.id.trim();
  if (!id) throw new Error('Give the assessment an id (e.g. "pa-2026-001").');
  const title = boundedText(input.title, LIMITS.assessmentTitleMin);
  if (!title) throw new Error('Assessment title needs at least 3 characters.');
  const kind = assertEnum(input.kind, ASSESSMENT_KINDS, 'assessment type') as AssessmentKind;
  const level = assertEnum(input.level, LEVELS, 'level') as Level;
  const competencyArea = assertEnum(input.competency_area ?? null, COMPETENCY_AREAS, 'competency area', {
    nullable: true,
  }) as CompetencyArea | null;

  const maxAttempts = Math.trunc(input.max_attempts ?? 2);
  if (!Number.isInteger(maxAttempts) || maxAttempts < 1 || maxAttempts > 999) {
    throw new Error('Max attempts must be a whole number between 1 and 999.');
  }

  const payload = {
    id,
    title,
    // description is NOT NULL (no length CHECK) — send '' rather than null.
    description: input.description?.trim() ?? '',
    kind,
    competency_area: competencyArea,
    level,
    questions: input.questions ?? [],
    practical_task_ids: input.practical_task_ids ?? [],
    hub_id: assertUuid(input.hub_id, 'Hub'),
    created_by: assertUuid(input.created_by, 'Creator'),
    creator_name: boundedText(input.creator_name, 2, 100) ?? 'Practitioner',
    is_published: input.is_published ?? true,
    due_at: input.due_at ? new Date(input.due_at).toISOString() : null,
    max_attempts: maxAttempts,
  };

  const { data, error } = await supabase.from('posted_assessments').insert(payload).select('*').single();
  throwIfDbError(error, 'Could not publish this assessment.');
  return data as PostedAssessment;
}

