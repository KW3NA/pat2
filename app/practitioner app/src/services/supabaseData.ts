export async function logCheckIn(input: {
  learner_id: string;
  practitioner_id: string;
  reasons: string[];
  notes: string;
  occurred_on?: string;
}): Promise<CheckInLog> {
  const learnerId = assertUuid(input.learner_id, 'Learner');
  const practitionerId = assertUuid(input.practitioner_id, 'Practitioner');
  const occurredOn = assertDate(input.occurred_on ?? todayIso(), 'Check-in date');
  // check_in_logs.reasons CHECK (jsonb_typeof(reasons) = 'array') — always send a real array.
  const reasons = Array.from(new Set((input.reasons ?? []).map((r) => r.trim()).filter(Boolean)));

  const { data, error } = await supabase
    .from('check_in_logs')
    .insert({
      learner_id: learnerId,
      practitioner_id: practitionerId,
      occurred_on: occurredOn,
      reasons,
      // notes is NOT NULL with DEFAULT '' — never send null.
      notes: input.notes?.trim() ?? '',
    })
    .select('id,learner_id,practitioner_id,occurred_on,reasons,notes,resolved,resolved_at,created_at')
    .single();
  throwIfDbError(error, 'Could not log the check-in.');
  return data as CheckInLog;
}

