/* --------------------------- Session registers ---------------------- */

/** Sessions registered by a practitioner, with attendees. */
export async function fetchSessions(practitionerId: string): Promise<SessionRegister[]> {
  const { data, error } = await supabase
    .from('session_registers')
    .select('id,hub_id,practitioner_id,session_date,notes,created_at,updated_at')
    .eq('practitioner_id', practitionerId)
    .order('session_date', { ascending: false });
  throwIfDbError(error, 'Could not load your sessions.');

  const rows = (data ?? []) as Omit<SessionRegister, 'attendees'>[];
  const ids = rows.map((r) => r.id);
  let attendees: { session_id: string; learner_id: string; present: boolean; users?: { name?: string } }[] = [];
  if (ids.length) {
    const res = await supabase
      .from('session_attendees')
      .select('session_id,learner_id,present,users:name(name)')
      .in('session_id', ids);
    throwIfDbError(res.error, 'Could not load attendance.');
    attendees = (((res.data ?? []) as any[]) as typeof attendees).map((a) => ({
      session_id: a.session_id,
      learner_id: a.learner_id,
      present: a.present,
      users: a.users,
    }));
  }
  return rows.map((r) => ({
    ...r,
    attendees: attendees
      .filter((a) => a.session_id === r.id)
      .map((a) => ({ learner_id: a.learner_id, present: a.present, name: a.users?.name })),
  }));
}

export async function registerSession(input: {
  /** hubs.id (uuid string) — stored in the text column session_registers.hub_id */
  hub_id: string;
  /** users.id (uuid string) of the practitioner */
  practitioner_id: string;
  /** YYYY-MM-DD */
  session_date: string;
  notes?: string;
  attendees: { learner_id: string; present: boolean }[];
}): Promise<SessionRegister> {
  const hubId = assertUuid(input.hub_id, 'Hub');
  const practitionerId = assertUuid(input.practitioner_id, 'Practitioner');
  const sessionDate = assertDate(input.session_date, 'Session date');
  const notes = input.notes?.trim() ? input.notes.trim() : null;
  const attendeeIds = Array.from(
    new Set(input.attendees.filter((a) => a.present).map((a) => assertUuid(a.learner_id, 'Learner'))),
  );

  const { data, error } = await supabase
    .from('session_registers')
    .insert({ hub_id: hubId, practitioner_id: practitionerId, session_date: sessionDate, notes })
    .select('id,hub_id,practitioner_id,session_date,notes,created_at,updated_at')
    .single();
  throwIfDbError(error, 'Could not register the session.');

  const session = data as Omit<SessionRegister, 'attendees'>;
  if (attendeeIds.length) {
    // session_attendees.session_id → FK session_registers(id) (that row exists now) and the
    // PK is (session_id, learner_id), so upsert keeps re-registration idempotent.
    const { error: attError } = await supabase.from('session_attendees').upsert(
      attendeeIds.map((learner_id) => ({ session_id: session.id, learner_id, present: true })),
      { onConflict: 'session_id,learner_id' },
    );
    throwIfDbError(attError, 'The session was saved, but attendance could not be recorded.');
  }
  return { ...session, attendees: attendeeIds.map((learner_id) => ({ learner_id, present: true })) };
}

