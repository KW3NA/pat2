/* ------------------------------------------------------------------ *
 * Validation helpers — mirror the schema's CHECK constraints so a bad *
 * value is caught in the app instead of coming back as error 23514.   *
 * ------------------------------------------------------------------ */

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
/** provinces.code CHECK (code ~ '^[A-Z]{2,3}$') */
const PROVINCE_CODE_RE = /^[A-Z]{2,3}$/;
/** date columns: session_registers.session_date, check_in_logs.occurred_on */
const ISO_DATE_RE = /^\d{4}-\d{2}-\d{2}$/;

export function assertUuid(value: string, label: string): string {
  if (!UUID_RE.test(String(value ?? ''))) {
    throw new Error(`${label} is not a valid record id. Reload and pick it from the list again.`);
  }
  return value;
}

export function assertDate(value: string, label: string): string {
  if (!ISO_DATE_RE.test(value) || Number.isNaN(Date.parse(value))) {
    throw new Error(`${label} must be a real date in YYYY-MM-DD form.`);
  }
  return value;
}

function assertEnum<T extends string>(
  value: T | null | undefined,
  allowed: readonly T[],
  label: string,
  { nullable = false }: { nullable?: boolean } = {},
): T | null {
  if (value === null || value === undefined || value === '') {
    if (nullable) return null;
    throw new Error(`Choose a ${label}.`);
  }
  if (!isIn(value, allowed)) throw new Error(`${value} is not an allowed ${label}.`);
  return value;
}

/** Local calendar date as 'YYYY-MM-DD' (never UTC-shifted like toISOString().slice(0,10)). */
export function todayIso(): string {
  const d = new Date();
  const pad = (n: number) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
}

