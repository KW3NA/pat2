/** Assignments created by a practitioner, with submissions. */
export async function fetchAssignments(createdBy: string): Promise<ModuleAssignment[]> {
  const { data, error } = await supabase
    .from('module_assignments')
    .select('id,course_id,module_id,title,instructions,due_at,created_by,created_at,updated_at')
    .eq('created_by', createdBy)
    .order('created_at', { ascending: false });
  throwIfDbError(error, 'Could not load assignments.');

  const rows = (data ?? []) as Omit<ModuleAssignment, 'submissions'>[];
  const ids = rows.map((r) => r.id);
  let subs: AssignmentSubmission[] = [];
  if (ids.length) {
    const res = await supabase
      .from('assignment_submissions')
      .select('id,assignment_id,learner_id,response,submitted_at,status,feedback')
      .in('assignment_id', ids)
      .order('submitted_at', { ascending: false });
    throwIfDbError(res.error, 'Could not load submissions.');
    subs = (res.data ?? []) as AssignmentSubmission[];
  }
  return rows.map((r) => ({ ...r, submissions: subs.filter((s) => s.assignment_id === r.id) }));
}

export async function createAssignment(input: {
  /** module_assignments.id has no default — supply a stable text id */
  id: string;
  course_id: string;
  module_id: string;
  title: string;
  instructions: string;
  due_at?: string | null;
  created_by: string;
}): Promise<ModuleAssignment> {
  const id = input.id.trim();
  if (!id) throw new Error('Give the assignment an id (e.g. "assign-2026-001").');
  const title = boundedText(input.title, LIMITS.assignmentTitleMin);
  if (!title) throw new Error('Assignment title needs at least 3 characters.');
  const instructions = boundedText(input.instructions, LIMITS.assignmentInstructionsMin);
  if (!instructions) throw new Error('Instructions need at least 5 characters.');
  const moduleId = input.module_id.trim();
  if (!moduleId) throw new Error('Pick the module this assignment belongs to.');

  // module_assignments.module_id → FK modules(id). Verify first so the practitioner gets a
  // clear message instead of Postgres error 23503.
  const module = await supabase.from('modules').select('id').eq('id', moduleId).maybeSingle();
  throwIfDbError(module.error, 'Could not verify the selected module.');
  if (!module.data) throw new Error('That module does not exist yet. Pick a module from the list.');

  const { data, error } = await supabase
    .from('module_assignments')
    .insert({
      id,
      course_id: input.course_id,
      module_id: moduleId,
      title,
      instructions,
      due_at: input.due_at ? new Date(input.due_at).toISOString() : null,
      created_by: assertUuid(input.created_by, 'Creator'),
    })
    .select('id,course_id,module_id,title,instructions,due_at,created_by,created_at,updated_at')
    .single();
  throwIfDbError(error, 'Could not create the assignment.');
  return { ...(data as Omit<ModuleAssignment, 'submissions'>), submissions: [] };
}

export async function reviewSubmission(submissionId: string, feedback: string) {
  const note = feedback.trim();
  if (!note) throw new Error('Add a short comment before marking this submission reviewed.');
  const { error } = await supabase
    .from('assignment_submissions')
    // status CHECK allows only 'submitted' | 'reviewed'.
    .update({ status: 'reviewed' satisfies SubmissionStatus, feedback: note })
    .eq('id', submissionId);
  throwIfDbError(error, 'Could not save your feedback.');
}

